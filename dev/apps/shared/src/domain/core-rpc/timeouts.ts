/** Same rule as the daemon: `seven_zip` / `7z`, or a `.7z` path when kind is omitted. */
export function vaultImportProbeTimeoutMs(params: { kind?: string; archivePath?: string }): number {
  const kind = params.kind?.trim().toLowerCase();
  if (kind === "seven_zip" || kind === "7z") return NO_DEADLINE_MS;
  if (!kind && params.archivePath?.trim().toLowerCase().endsWith(".7z")) return NO_DEADLINE_MS;
  return CORE_RPC_TIMEOUT_MS[CORE_RPC_COMMANDS.VAULT_IMPORT_PROBE];
}

/** A setup that copies a phone's private data folder into the grant is a job. */
export function vaultRootSetupPathTimeoutMs(params: { adoptPrivateRoot?: boolean }): number {
  return params.adoptPrivateRoot ? NO_DEADLINE_MS : OPERATION_LIMIT_MS;
}
